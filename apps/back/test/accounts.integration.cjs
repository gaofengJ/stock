/* Run only against a disposable, explicitly named local MySQL test database. */
require('reflect-metadata');
const assert = require('node:assert/strict');
const { randomBytes } = require('node:crypto');
const { Test } = require('@nestjs/testing');
const { DataSource } = require('typeorm');
const { FastifyAdapter } = require('@nestjs/platform-fastify');
const { APP_GUARD, Reflector } = require('@nestjs/core');
const { AuthModule } = require('../dist/modules/auth/auth.module');
const { AuthService, COOKIE, digest } = require('../dist/modules/auth/auth.service');
const { AuthGuard } = require('../dist/modules/auth/auth.guard');
const { Accounts1790467200000 } = require('../dist/migrations/1790467200000-Accounts');
const { TransformInterceptor } = require('../dist/interceptors/transform.interceptor');
const { hashPassword } = require('../dist/modules/auth/password');
const { ActiveFundsEntity } = require('../dist/modules/source/active-funds/active-funds.entity');
const { DailyTaskService } = require('../dist/modules/daily-task/daily-task.service');
const { DataLockService } = require('../dist/modules/admin/data-lock.service');
const { JobsService } = require('../dist/modules/admin/jobs.service');
const { LogsService } = require('../dist/modules/admin/logs.service');
const { redact } = require('../dist/modules/auth/redact');
const { Global, Module, ValidationPipe } = require('@nestjs/common');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');

async function main() {
  const database = process.env.AUTH_TEST_DATABASE;
  assert.ok(/^stock_auth_test_[a-z0-9_]+$/.test(database || ''), 'AUTH_TEST_DATABASE must name a disposable stock_auth_test_* database');
  const options = { type: 'mysql', host: '127.0.0.1', port: Number(process.env.AUTH_TEST_PORT || 33387), username: process.env.AUTH_TEST_USER || 'root', password: process.env.AUTH_TEST_PASSWORD || '', timezone: 'Z', logging: false };
  const server = await new DataSource(options).initialize();
  const alreadyExists = await server.query('SELECT SCHEMA_NAME FROM information_schema.SCHEMATA WHERE SCHEMA_NAME=?',[database]);
  if(alreadyExists.length) { await server.destroy(); throw new Error('Refusing existing test database; choose a new name'); }
  await server.query('CREATE DATABASE ' + database + ' CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci');
  const db = await new DataSource({ ...options, database, entities: [ActiveFundsEntity] }).initialize();
  let app; let temp;
  try {
    assert.equal((await db.query('SHOW TABLES')).length, 0, 'Use a new database name for each run');
    const q = db.createQueryRunner(); const migration = new Accounts1790467200000();
    await migration.up(q);
    const [initial] = await db.query("SELECT id,password FROM t_user WHERE username='mufeng'");
    assert.ok(initial.password.startsWith('$argon2id$'));
    // Test idempotence without ever storing the actual initial administrator password in a test.
    const adminPassword = randomBytes(18).toString('base64url');
    const encoded = await hashPassword(adminPassword);
    await db.query('UPDATE t_user SET password=? WHERE id=?', [encoded, initial.id]);
    await migration.up(q);
    assert.equal((await db.query('SELECT password FROM t_user WHERE id=?', [initial.id]))[0].password, encoded);
    await q.release();
    class TestDatabase {}
    Global()(TestDatabase); Module({ providers: [{ provide: DataSource, useValue: db }], exports: [DataSource] })(TestDatabase);
    const module = await Test.createTestingModule({ imports: [TestDatabase, AuthModule], providers: [{ provide: APP_GUARD, useClass: AuthGuard }] }).compile();
    const adapter = new FastifyAdapter();
    await adapter.register(require('@fastify/cookie'));
    app = module.createNestApplication(adapter, { logger: false });
    app.useGlobalPipes(new ValidationPipe({ transform:true,whitelist:true,forbidNonWhitelisted:true,transformOptions:{enableImplicitConversion:true} }));
    app.setGlobalPrefix('api'); app.useGlobalInterceptors(new TransformInterceptor(new Reflector()));
    await app.init(); await adapter.getInstance().ready();
    const inject = (method, url, payload, client = {}, extra = {}) => app.inject({ method, url: '/api' + url, payload, headers: { ...(client.cookie ? { cookie: client.cookie } : {}), ...(client.csrf ? { 'x-csrf-token': client.csrf } : {}), ...extra } });
    const token = async () => { const r = await inject('GET', '/auth/csrf'); assert.equal(r.statusCode, 200); assert.match(r.headers['set-cookie'], /HttpOnly/); assert.match(r.headers['set-cookie'], /SameSite=Lax/); return { cookie: r.headers['set-cookie'].split(';')[0], csrf: r.json().data.csrfToken }; };
    const login = async (username, password) => { const c = await token(); const r = await inject('POST', '/auth/login', { username, password }, c); assert.equal(r.statusCode, 201, r.body); return { cookie: r.headers['set-cookie'].split(';')[0], csrf: r.json().data.csrfToken, user: r.json().data.user }; };
    assert.equal((await inject('GET', '/auth/me')).statusCode, 401);
    assert.equal((await inject('POST', '/auth/register', { username: 'alice', password: 'test-password-123' })).statusCode, 403);
    const anon = await token();
    assert.equal((await inject('POST', '/auth/register', { username: 'numberpass', password: 1234567890123 }, anon)).statusCode, 400);
    assert.equal((await inject('POST', '/auth/register', { username: 'alice', password: 'test-password-123', roles: ['admin'] }, anon)).statusCode, 400);
    assert.equal((await inject('POST', '/auth/register', { username: 'alice', password: 'test-password-123' }, anon, { origin: 'https://untrusted.invalid' })).statusCode, 403);
    assert.equal((await inject('POST', '/auth/register', { username: '  Alice  ', password: 'test-password-123' }, anon)).statusCode, 201);
    assert.equal((await inject('POST', '/auth/register', { username: 'ALICE', password: 'test-password-123' }, anon)).statusCode, 409);
    assert.equal((await inject('POST', '/auth/register', { username: 'mufeng', password: 'test-password-123' }, anon)).statusCode, 409);
    let user = await login('alice', 'test-password-123');
    const admin = await login('mufeng', adminPassword);
    assert.equal(user.user.permissions.includes('users:manage'), false);
    assert.ok(user.user.permissions.includes('strategy:read'));
    assert.equal((await inject('GET', '/admin/users', undefined, user)).statusCode, 403);
    assert.equal((await inject('POST', '/admin/users', { username: 'evil', password: 'test-password-123' }, user)).statusCode, 403);
    assert.equal((await inject('PATCH', '/admin/users/' + admin.user.id, { active: 'false' }, admin)).statusCode, 400);
    assert.equal((await inject('PATCH', '/admin/users/' + admin.user.id, { active: false }, admin)).statusCode, 409);
    assert.equal((await inject('PATCH', '/admin/users/' + admin.user.id, { roleIds: [] }, admin)).statusCode, 409);
    assert.equal((await inject('GET', '/admin/users', undefined, admin)).body.includes(encoded), false);
    const roleResponse = await inject('POST', '/admin/roles', { code: 'reviewer', name: 'Reviewer', permissions: ['sync:read'] }, admin);
    assert.equal(roleResponse.statusCode, 201, roleResponse.body);
    const roleId = roleResponse.json().data.id;
    const defaultRole = user.user.roles.find(r => r.code === 'user').id;
    assert.equal((await inject('PATCH', '/admin/users/' + user.user.id, { roleIds: [defaultRole, roleId] }, admin)).statusCode, 200);
    const merged = (await inject('GET', '/auth/me', undefined, user)).json().data;
    assert.ok(merged.permissions.includes('sync:read') && merged.permissions.includes('strategy:read'));
    assert.equal((await inject('DELETE', '/admin/roles/' + roleId, undefined, admin)).statusCode, 409);
    assert.equal((await inject('PATCH', '/admin/roles/' + defaultRole, { code: 'user', name: '普通用户', permissions: ['strategy:read'] }, admin)).statusCode, 200);
    const reduced = (await inject('GET', '/auth/me', undefined, user)).json().data;
    assert.deepEqual(new Set(reduced.permissions), new Set(['strategy:read', 'sync:read']));
    const repeatRunner = db.createQueryRunner(); await migration.up(repeatRunner); await repeatRunner.release();
    assert.equal((await inject('GET', '/auth/me', undefined, user)).json().data.permissions.length, 2);
    assert.equal((await inject('PATCH', '/admin/users/' + user.user.id, { active: false }, admin)).statusCode, 200);
    assert.equal((await inject('GET', '/auth/me', undefined, user)).statusCode, 401);
    await inject('PATCH', '/admin/users/' + user.user.id, { active: true }, admin);
    user = await login('alice', 'test-password-123');
    const second = await login('alice', 'test-password-123');
    assert.equal((await inject('POST', '/admin/users/' + user.user.id + '/reset-password', { password: 'temporary-password-123' }, admin)).statusCode, 201);
    assert.equal((await inject('GET', '/auth/me', undefined, second)).statusCode, 401);
    user = await login('alice', 'temporary-password-123');
    assert.equal(user.user.mustChangePassword, true);
    assert.equal((await inject('PATCH', '/users/me', { nickname: 'blocked' }, user)).statusCode, 403);
    assert.equal((await inject('PATCH', '/auth/password', { currentPassword: 'wrong-password', newPassword: 'new-test-password' }, user)).statusCode, 400);
    assert.equal((await inject('PATCH', '/auth/password', { currentPassword: 'temporary-password-123', newPassword: 'new-test-password' }, user)).statusCode, 200);
    assert.equal((await inject('GET', '/auth/me', undefined, user)).statusCode, 401);
    user = await login('alice', 'new-test-password');
    const rawToken = user.cookie.split('=')[1];
    const [stored] = await db.query('SELECT * FROM t_auth_session WHERE token_hash=?', [digest(rawToken)]);
    assert.equal(JSON.stringify(stored).includes(rawToken), false);
    await db.query('UPDATE t_auth_session SET last_seen_at=DATE_SUB(UTC_TIMESTAMP(),INTERVAL 25 HOUR) WHERE id=?', [stored.id]);
    assert.equal((await inject('GET', '/auth/me', undefined, user)).statusCode, 401);
    user = await login('alice', 'new-test-password');
    await db.query('UPDATE t_auth_session SET expires_at=DATE_SUB(UTC_TIMESTAMP(),INTERVAL 1 SECOND) WHERE token_hash=?', [digest(user.cookie.split('=')[1])]);
    assert.equal((await inject('GET', '/auth/me', undefined, user)).statusCode, 401);
    user = await login('alice', 'new-test-password');
    assert.equal((await inject('POST', '/auth/logout', undefined, user)).statusCode, 201);
    assert.equal((await inject('GET', '/auth/me', undefined, user)).statusCode, 401);
    const auth = app.get(AuthService);
    const locks = new DataLockService(db);
    await db.query('CREATE TABLE t_source_active_funds (id INT AUTO_INCREMENT PRIMARY KEY,created_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),updated_at DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6),name VARCHAR(16) NOT NULL,orgs TEXT,`desc` TEXT)');
    const daily = new DailyTaskService(db, locks);
    const fixtures=[{name:'A',orgs:'one'},{name:'B',orgs:'two'}];
    await daily.replaceSnapshot(ActiveFundsEntity,fixtures);
    await daily.replaceSnapshot(ActiveFundsEntity,[{name:'A',orgs:'updated'},{name:'B',orgs:'two'}]);
    await assert.rejects(daily.replaceSnapshot(ActiveFundsEntity,[]));
    await assert.rejects(daily.replaceSnapshot(ActiveFundsEntity,[{name:'A'}]));
    await assert.rejects(daily.replaceSnapshot(ActiveFundsEntity,[{name:'C'},{name:'too-long-name-for-this-column'}]));
    assert.equal((await db.query("SELECT orgs FROM t_source_active_funds WHERE name='A'"))[0].orgs,'updated');
    assert.equal(Number((await db.query('SELECT COUNT(*) n FROM t_source_active_funds'))[0].n),2);
    const fake = { import: async () => {}, bulkImport: async (start, end, progress) => { await progress(start); await progress(end); } };
    const jobs = new JobsService(db, fake, auth, locks);
    const job = await jobs.create(admin.user, '2026-01-02', '2026-01-03');
    assert.equal((await jobs.create(admin.user, '2026-01-02', '2026-01-03')).id, job.id);
    const blocker = db.createQueryRunner(); await blocker.connect();
    const lockName = 'stock-sync:' + require('node:crypto').createHash('sha256').update(database).digest('hex').slice(0, 40);
    await blocker.query('SELECT GET_LOCK(?,0)', [lockName]); await jobs.tick();
    assert.equal((await jobs.detail(job.id)).status, 'queued');
    await blocker.query('SELECT RELEASE_LOCK(?)', [lockName]); await blocker.release();
    await jobs.tick(); assert.equal((await jobs.detail(job.id)).status, 'success');
    fake.import = async () => { await db.query("INSERT INTO t_sync_run(task,trade_date,status) VALUES ('daily','2026-01-04','pending')"); };
    const partial = await jobs.create(admin.user,'2026-01-04','2026-01-04'); await jobs.tick();
    assert.equal((await jobs.detail(partial.id)).status,'pending');
    const revoked = await jobs.create(user.user,'2026-01-06','2026-01-06'); await jobs.tick();
    assert.equal((await jobs.detail(revoked.id)).status,'failed');
    fake.import = async () => { throw new Error('fixture source failure'); };
    const bad = await jobs.create(admin.user, '2026-01-05', '2026-01-05'); await jobs.tick();
    assert.equal((await jobs.detail(bad.id)).status, 'failed');
    const retry = await jobs.create(admin.user, '2026-01-05', '2026-01-05'); assert.notEqual(retry.id, bad.id);
    await db.query("UPDATE t_admin_job SET status='running' WHERE id=?", [retry.id]); await jobs.onApplicationBootstrap();
    assert.equal((await jobs.detail(retry.id)).status, 'interrupted');
    temp = await fs.mkdtemp(path.join(os.tmpdir(), 'stock-auth-logs-')); process.env.LOG_DIR = temp;
    const logfile = path.join(temp, 'stock-back.2026-01-02.log');
    await fs.writeFile(logfile, JSON.stringify({ level: 'error', context: 'Fixture', message: 'broken', password: 'sensitive' }) + '\ninvalid\n' + JSON.stringify({ level: 'info', context: 'Other', message: 'okay' }) + '\n');
    await fs.writeFile(path.join(temp, 'stock-back-error.2026-01-02.log'), JSON.stringify({ level: 'error', message: 'duplicate' }) + '\n');
    const logs = new LogsService(db);
    const query = { page: 1, pageSize: 1, startDate: '2026-01-02', endDate: '2026-01-02' };
    const logResult = await logs.application(query);
    assert.equal(logResult.total, 2); assert.equal(logResult.items.length, 1); assert.equal(logResult.malformed, 1); assert.equal(logResult.levels.error, 1);
    assert.equal(JSON.stringify(logResult).includes('sensitive'), false);
    assert.equal((await logs.application({ ...query, keyword: 'okay' })).total, 1);
    assert.equal((await logs.application({ ...query, startDate: '2026-01-04', endDate: '2026-01-04' })).total, 0);
    await assert.rejects(logs.application({ ...query, endDate: '2026-02-01' }));
    assert.equal(JSON.stringify(redact({ nested: { password: 'x', cookie: 'y', token: 'z' } })).includes('"x"'), false);
    const audit = await db.query('SELECT detail FROM t_auth_audit');
    assert.equal(JSON.stringify(audit).includes('temporary-password-123'), false);
    // Independent login budget is enforced even without the general throttler.
    let last;
    for (let i = 0; i < 21; i++) last = await inject('POST', '/auth/login', { username: 'notregistered', password: 'wrong-password' }, anon);
    assert.equal(last.statusCode, 429);
    const other = await auth.register({username:'other_admin',password:'other-admin-fixture'});
    const [adminRole] = await db.query("SELECT id FROM t_role WHERE code='admin'");
    await auth.updateUser(admin.user, other.id, {roleIds:[adminRole.id]});
    const results = await Promise.allSettled([auth.updateUser(admin.user, admin.user.id, {active:false}),auth.updateUser(admin.user, other.id, {active:false})]);
    assert.equal(results.filter(r=>r.status==='fulfilled').length,1);
    await auth.ensureAdministrator(db.manager);
    console.info('PASS: migration, registration, CSRF, RBAC, multi-role union, last admin, disabled users, password reset, expiry, logout, jobs, lock contention, logs and audit redaction.');
  } finally {
    if (app) await app.close();
    if (db.isInitialized) await db.destroy();
    await server.query('DROP DATABASE ' + database); await server.destroy();
    if (temp) await fs.rm(temp, { recursive: true, force: true });
  }
}
main().catch(e => { console.error(e instanceof assert.AssertionError ? e.message : e.message?.startsWith('Account migration:') ? e.message : 'Integration failed: ' + e.constructor.name + ' (database parameters omitted)'); console.error(e.stack?.split('\n').filter(line => line.includes('accounts.integration.cjs')).join('\n')); process.exitCode = 1; });
